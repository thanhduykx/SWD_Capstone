using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using CPMS.BLL.Testing;

namespace CPMS.API.Controllers;

[ApiController]
[Route("api/test-support")]
[AllowAnonymous]
public sealed class TestSupportController(
    IWebHostEnvironment environment,
    IConfiguration configuration,
    ITestDataResetService resetService) : ControllerBase
{
    private string DefaultTestPassword => configuration.GetValue<string>("TestData:DefaultPassword") ?? string.Empty;
    private const string LecturerRole = "Lecturer";
    private static readonly string[] DatasetChecks =
    [
        "GET /api/review-sessions/my",
        "GET /api/review-submissions/my",
        "GET /api/defense-management/my-board-sessions",
        "GET /api/review-scheduling/rounds?semesterId={activeSemesterId}"
    ];

    [HttpGet("swagger-guide")]
    public ActionResult<SwaggerTestGuideResponse> GetSwaggerGuide()
    {
        if (!IsEnabled())
        {
            return NotFound();
        }

        return Ok(new SwaggerTestGuideResponse(
            "Local Swagger helper for FE/manual API testing.",
            [
                "Call POST /api/auth/login with a test account.",
                "Copy accessToken from the login response.",
                "Click Authorize in Swagger and paste the accessToken value only.",
                "Use GET endpoints first to get real ids. Do not guess semesterId, lecturerId, groupId, sessionId, or submissionId.",
                "Use the role matrix below before calling protected endpoints."
            ],
            TestAccounts(),
            RoleGroups(),
            [
                "DateOnly query/body values use yyyy-MM-dd, for example 2026-06-15.",
                "DateTime body values use ISO format, for example 2026-06-15T00:00:00Z.",
                "Review dayOfWeek uses Monday=1 through Saturday=6.",
                "Review slot must be 1 through 5; defense slots are separate.",
                "A group leader submits exactly five distinct student-availability slots while the round is Open.",
                "Lecturer availability is isolated by roundId; moderator scheduling uses only availability submitted for that exact review round.",
                "Common enum values: Student, Lecturer, TrainingDepartment, Review1, Review2, Review3, Defense1, Defense2, Draft, Published, Cancelled, BaoVe, Nguoi.",
                "Account username is generated by backend from fullName and identityCode. Example: Duong Thanh Thanh Duy + SE194673 -> DuyDTTSE194673."
            ],
            [
                "Auth flow: POST /api/auth/login -> Authorize -> call protected endpoint.",
                "Account flow: login as moderator -> GET /api/accounts -> POST /api/accounts.",
                "Lecturer availability flow: get an Open roundId -> PUT /api/review-availability/week?roundId=... -> POST /api/review-availability/week/submit?roundId=... -> GET /api/review-availability/week?roundId=....",
                "Review scheduling flow: Open round -> student/lecturer availability -> Close round -> random/bulk assign -> publish.",
                "Review checklist flow: login as lecturer -> GET /api/review-sessions/my -> GET /api/review-submissions/{submissionId} -> PUT draft -> POST submit.",
                "Defense flow: login as moderator to create round/board/session -> login as board lecturer -> resolve session -> chairman starts -> members submit group comments -> chairman closes."
            ]));
    }

    [HttpGet("test-accounts")]
    public ActionResult<IReadOnlyCollection<TestAccountResponse>> GetTestAccounts()
    {
        if (!IsEnabled())
        {
            return NotFound();
        }

        return Ok(TestAccounts());
    }

    [HttpPost("clear-data")]
    public async Task<IActionResult> ClearData(CancellationToken cancellationToken)
    {
        if (!IsEnabled())
        {
            return NotFound();
        }

        await resetService.ResetAsync(cancellationToken);

        return Ok(new { message = "All database tables truncated successfully and default seed data restored." });
    }

    /// <summary>
    /// Opt-in upsert of shared lecturer sample data on the active semester (same domain as website workflows).
    /// Additive only — does not truncate and does not change review/defense business rules.
    /// </summary>
    [HttpPost("ensure-dataset")]
    public async Task<IActionResult> EnsureDataset(
        [FromServices] CPMS.BLL.Abstractions.Persistence.IDatabaseLifecycleService lifecycle,
        CancellationToken cancellationToken)
    {
        ArgumentNullException.ThrowIfNull(lifecycle);
        if (!IsEnabled())
        {
            return NotFound();
        }

        await lifecycle.EnsureMobileLecturerDatasetAsync(cancellationToken);
        return Ok(new
        {
            message = "Shared lecturer dataset ensured on the active semester (same data space as website).",
            loginEmail = "minhnd.gv24001@fpt.edu.vn",
            password = DefaultTestPassword,
            note = "Groups SE2601–SE2606, published review/defense rows are visible to both web and mobile APIs.",
            check = DatasetChecks
        });
    }

    private bool IsEnabled() =>
        environment.IsDevelopment() && configuration.GetValue<bool>("Swagger:ExposeTestSupport");

    private IReadOnlyCollection<TestAccountResponse> TestAccounts() =>
    [
        new("TrainingDepartment", "pdt.dieuphoi@fpt.edu.vn", DefaultTestPassword, "Phòng Đào tạo — điều phối đồ án."),
        new(LecturerRole, "minhnd.gv24001@fpt.edu.vn", DefaultTestPassword, "GV24001 Nguyễn Đức Minh — review + hội đồng (chairman)."),
        new(LecturerRole, "hapt.gv24002@fpt.edu.vn", DefaultTestPassword, "GV24002 Phạm Thu Hà — reviewer / thư ký hội đồng."),
        new(LecturerRole, "namlh.gv24003@fpt.edu.vn", DefaultTestPassword, "GV24003 Lê Hoàng Nam — reviewer / thành viên hội đồng."),
        new("Student", "maunv.se199999@fpt.edu.vn", DefaultTestPassword, "Use for student visibility checks.")
    ];

    private static IReadOnlyCollection<RoleEndpointGroupResponse> RoleGroups() =>
    [
        new("Anonymous", ["POST /api/auth/login", "POST /api/auth/refresh", "POST /api/auth/google"]),
        new("TrainingDepartment", [
            "GET/POST/PATCH /api/accounts including role account creation",
            "GET/POST /api/semesters",
            "GET /api/review-scheduling/board",
            "POST /api/review-scheduling/random-assign",
            "POST/PATCH /api/review-sessions",
            "POST /api/review-schedules/publish",
            "GET /api/review-submissions/export.zip",
            "GET/POST /api/defense-management/*"
        ]),
        new(LecturerRole, [
            "GET/PUT /api/review-availability/week",
            "POST /api/review-availability/week/submit",
            "GET /api/review-sessions/my",
            "GET/PUT/POST /api/review-submissions/{submissionId}",
            "GET /api/defense-management/my-board-sessions",
            "GET/POST /api/defense-sessions/* when assigned to the council"
